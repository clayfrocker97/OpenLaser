// Verify the API contract without changing the workspace or requiring a clean git tree.
import { mkdtempSync, readdirSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { bindingText } from './binding-format.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const output = mkdtempSync(join(tmpdir(), 'openlaser-bindings-'));
try {
  const test = spawnSync('cargo', ['test', '--workspace', '--all-features', '--locked', '--lib', 'export_bindings', '--', '--test-threads=1'], {
    cwd: root, env: { ...process.env, TS_RS_EXPORT_DIR: output }, stdio: 'inherit',
  });
  if (test.status !== 0) throw new Error('TypeScript export failed.');
  const names = (dir) => readdirSync(dir).filter((name) => name.endsWith('.ts') || name === 'recipe-policy.json').sort();
  const current = join(root, 'ui/src/api/bindings');
  const files = names(output);
  const changed = files.filter((name) => {
    try { return bindingText(readFileSync(join(output, name))) !== readFileSync(join(current, name), 'utf8'); }
    catch { return true; }
  });
  changed.push(...names(current).filter((name) => !files.includes(name)));
  const lines = files.filter((name) => name.endsWith('.ts')).map((name) => name.slice(0, -3)).map((name) => `export type { ${name} } from './bindings/${name}';`);
  const barrel = `// Generated by scripts/barrel.mjs from the ts-rs bindings. Do not edit.\n${lines.join('\n')}\n`;
  if (readFileSync(join(root, 'ui/src/api/index.ts'), 'utf8') !== barrel) changed.push('index.ts');
  if (changed.length) throw new Error(`Regenerate the API bindings: ${changed.join(', ')}`);
  console.log(`${files.length} API bindings reproduce exactly.`);
} finally {
  rmSync(output, { recursive: true, force: true });
}
